public class Department {
    private String DeptName;
    private String DeptCode;
    public String getDeptName() {
        return DeptName;
    }
    public void setDeptName(String deptName) {
        DeptName = deptName;
    }
    public String getDeptCode() {
        return DeptCode;
    }
    public void setDeptCode(String deptCode) {
        DeptCode = deptCode;
    }
    
}
